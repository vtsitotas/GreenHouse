def for_param(key):
    """Explanation of a catalogue key; RTC:<variable> rows are generated from the
    firmware's RTC_DATA_ATTR declarations, so they share one generic text."""
    if key in CATALOGUE:
        return CATALOGUE[key]
    if key.startswith("RTC:"):
        return (f"Μνήμη ύπνου που πιάνει η μεταβλητή {key[4:]} του firmware.",
                "Διαβάζεται από τον κώδικα: μέγεθος τύπου × πλήθος στοιχείων.")
    return None
